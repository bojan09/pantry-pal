// ---------- compile ----------

const byName = new Map(CATALOG.map((i) => [i.name, i.id]));

export interface StarterRecipe {
  recipe: Recipe;
  ingredients: RecipeIngredient[];
  steps: RecipeStep[];
}

function compile(d: Def): StarterRecipe {
  return {
    recipe: {
      id: d.id,
      name: d.name,
      summary: d.summary,
      cuisine: d.cuisine,
      category: d.category,
      tags: d.tags,
      prepMinutes: d.prep,
      cookMinutes: d.cook,
      difficulty: d.difficulty,
      servings: d.servings,
      favorite: false,
      isStarter: true,
      art: d.art,
      createdAt: 0,
      updatedAt: 0,
    },
    ingredients: d.ingredients.map(([name, quantity, unit, opt], i) => {
      const ingredientId = byName.get(name);
      if (!ingredientId) throw new Error(`Starter recipe "${d.id}": unknown ingredient "${name}"`);
      return {
        id: `${d.id}-i${i}`,
        recipeId: d.id,
        ingredientId,
        quantity,
        unit,
        position: i,
        ...(opt ? { optional: true } : {}),
      };
    }),
    steps: d.steps.map((s, i) => {
      const [text, minutes] = typeof s === 'string' ? [s, undefined] : s;
      return {
        id: `${d.id}-s${i}`,
        recipeId: d.id,
        position: i,
        text,
        ...(minutes ? { timerSeconds: minutes * 60 } : {}),
      };
    }),
  };
}

export const STARTER_RECIPES: StarterRecipe[] = DEFS.map(compile);
