// Writes docs/LICENSES.md from the packages that ship in the production bundle.
// Run:  node scripts/licenses.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const tree = JSON.parse(
  execFileSync('npm', ['ls', '--omit=dev', '--all', '--json'], { cwd: root, maxBuffer: 64 * 1024 * 1024 }).toString(),
);

const seen = new Map();
const walk = (deps) => {
  for (const [name, info] of Object.entries(deps ?? {})) {
    if (seen.has(name)) continue;
    let pkg;
    try {
      pkg = JSON.parse(readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8'));
    } catch {
      continue;
    }
    const lic = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? (pkg.licenses?.map((l) => l.type).join(' OR ') || 'UNKNOWN'));
    seen.set(name, { version: pkg.version, license: lic });
    walk(info.dependencies);
  }
};
walk(tree.dependencies);

const rows = [...seen.entries()].sort(([a], [b]) => a.localeCompare(b));
const OK = /^(MIT|ISC|Apache-2\.0|BSD-[23]-Clause|0BSD|OFL-1\.1|BlueOak-1\.0\.0|CC0-1\.0|\(?(MIT|Apache-2\.0|BSD-[23]-Clause|ISC|OFL-1\.1)( (OR|AND) (MIT|Apache-2\.0|BSD-[23]-Clause|ISC|OFL-1\.1))*\)?)$/;
const odd = rows.filter(([, v]) => !OK.test(v.license));

const byLicense = new Map();
for (const [, v] of rows) byLicense.set(v.license, (byLicense.get(v.license) ?? 0) + 1);

let md = `# Third-party licenses\n\nGenerated by \`node scripts/licenses.mjs\`. Production dependencies only (what ships in the app); build and test tools are not included.\n\nPantryPal itself adds no paid service, tracker or proprietary dependency. Illustrations are original SVG drawings made for the project. Fonts are Fraunces and Inter (SIL Open Font License 1.1), self-hosted.\n\n## Summary\n\n| License | Packages |\n| --- | ---: |\n${[...byLicense.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`).join('\n')}\n\n`;
md += odd.length ? `## Needs a look\n\n${odd.map(([n, v]) => `- ${n}@${v.version}: ${v.license}`).join('\n')}\n\n` : '## Needs a look\n\nNothing: every package uses a permissive license.\n\n';
md += `## All packages\n\n| Package | Version | License |\n| --- | --- | --- |\n${rows.map(([n, v]) => `| ${n} | ${v.version} | ${v.license} |`).join('\n')}\n`;
writeFileSync(join(root, 'docs/LICENSES.md'), md);
console.log(`${rows.length} packages, ${odd.length} needing review`);
process.exit(odd.length ? 1 : 0);
